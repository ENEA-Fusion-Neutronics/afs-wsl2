# Final instructions. Args: test_mode kern kimg
print_next_steps() {
  local test_mode="$1" kern="$2" kimg="$3" out="$LAUNCH_DIR/$OUTNAME"
  if [[ $test_mode == 1 ]]; then
    cat <<MSG

SELF-BUILT KERNEL ($KVER) + modules from the same build, NOT Microsoft's binary.
  kernel  : $LAUNCH_DIR/$kimg
  modules : $out
Build and consistency (vermagic/CRC) verified here; NOT booted on WSL (running: $RUNKVER).

To try it (not done by this script; nothing was copied to Windows):
  1. cp "$LAUNCH_DIR/$kimg" "$out" /mnt/e/wsl/
  2. In %UserProfile%\\.wslconfig, section [wsl2]:
         kernel=E:\\\\wsl\\\\$kimg
         kernelModules=E:\\\\wsl\\\\$OUTNAME
  3. PowerShell: wsl --shutdown ; then: uname -r ; ./afs-setup.sh check
To go back: comment out the two lines in .wslconfig and run wsl --shutdown again.
MSG
    return 0
  fi
  cat <<MSG

VHDX ready: $out
$([[ $kern == 1 ]] && echo "Test kernel image (build verified, NOT boot-tested): $LAUNCH_DIR/$kimg
For kernel= still use the stock Microsoft copy shown below.")

Next steps (not run by this script; no file was copied to Windows):
  1. Copy the VHDX AND Microsoft's stock kernel (same release) to a Windows drive:
         cp "$out" /mnt/e/wsl/
         # typical path of the stock kernel: check it
         cp "/mnt/c/Program Files/WSL/tools/kernel" /mnt/e/wsl/kernel-$KVER
         file /mnt/e/wsl/kernel-$KVER      # must report "version $KVER"
  2. In %UserProfile%\\.wslconfig, section [wsl2], BOTH lines are needed (doubled backslashes):
         kernel=E:\\\\wsl\\\\kernel-$KVER
         kernelModules=E:\\\\wsl\\\\$OUTNAME
     (WSL refuses kernelModules= without kernel=.)
  3. PowerShell: wsl --shutdown ; then reopen WSL and check:
         uname -r ; ls /lib/modules/\$(uname -r)/extra ; ./afs-setup.sh check

The VHDX REPLACES the stock one (it contains the stock modules + ours) and is tied to $KVER.
After \`wsl --update\` WSL stays on the old kernel/VHDX until you redo the procedure; to switch
to the new kernel right away, comment out the two lines in .wslconfig (no AFS) and repeat the
steps.
MSG
}

# Prints the tag to test (validated, and newer than the running release for --latest).
# Args: latest(0|1) target(tag or empty). Messages go to stderr: stdout is the tag only.
resolve_test_target() {
  local latest="$1" target="$2" mm cur tk repo=https://github.com/microsoft/WSL2-Linux-Kernel.git
  mm="$(cut -d. -f1,2 <<<"$KVER")"; cur="${KVER%%-*}"
  if [[ $latest == 1 ]]; then
    log "Looking for the newest linux-msft-wsl-$mm.* tag" >&2
    target="$(git ls-remote --tags "$repo" "refs/tags/linux-msft-wsl-$mm.*" |
              awk '{print $2}' | sed 's|refs/tags/||' | grep -v '\^{}' | sort -V | tail -1)"
    [[ -n "$target" ]] || die "no linux-msft-wsl-$mm.* tag found."
  fi
  [[ "$target" == linux-msft-wsl-* ]] || die "--target-tag must look like linux-msft-wsl-X.Y.Z[.N]"
  tk="${target#linux-msft-wsl-}"
  [[ "$tk" =~ ^[0-9]+\.[0-9]+\.[0-9]+(\.[0-9]+)?$ ]] || die "invalid tag version: '$tk'"
  git ls-remote --exit-code --tags "$repo" "refs/tags/$target" >/dev/null ||
    die "tag '$target' not found in the Microsoft repository."
  if [[ $latest == 1 && "$(printf '%s\n%s\n' "$cur" "$tk" | sort -V | tail -1)" == "$cur" ]]; then
    die "no tag newer than $cur ($tk)."
  fi
  echo "$target"
}

cmd_build() {
  local only=both debs="$LAUNCH_DIR/openafs-debs" layout=flat seed="" ksuffix=-built target=""
  local force=0 req=0 kern=0 latest=0
  while (($#)); do
    case "$1" in
      --only)             only="${2:?}"; shift ;;
      --debs)             debs="$(realpath "${2:?}")"; shift ;;
      --require-openafs)  req=1 ;;
      --layout)           layout="${2:?}"; shift ;;
      --seed)             seed="$(realpath "${2:?}")"; shift ;;
      --kernel)           kern=1 ;;
      --latest)           latest=1 ;;
      --target-tag)       target="${2:?}"; shift ;;
      --kernel-suffix)    ksuffix="${2?}"; shift ;;
      --force)            force=1 ;;
      *) die "unknown option: $1" ;;
    esac
    shift
  done
  [[ "$only" == kafs || "$only" == openafs || "$only" == both ]] || die "--only: kafs|openafs|both"
  [[ "$layout" == flat || "$layout" == nested ]] || die "--layout: flat|nested"

  need_wsl_kernel; need_podman

  # Test mode: switch the target to another (newer) release. This is the only place where
  # KVER, TAG, OUTNAME and WORK are redefined; RUNKVER keeps the running release.
  local test_mode=0
  if [[ $latest == 1 || -n "$target" ]]; then
    test_mode=1; kern=1
    target="$(resolve_test_target "$latest" "$target")"
    KVER="${target#linux-msft-wsl-}-microsoft-standard-WSL2"
    TAG="$target"
    OUTNAME="wsl-modules-$KVER.vhdx"
    WORK="$WORK/test-${target#linux-msft-wsl-}"     # tree cache separate from the real one
    log "TEST MODE: $target (running: $RUNKVER)"
  fi
  [[ "$ksuffix" =~ ^[A-Za-z0-9._-]*$ ]] ||
    die "--kernel-suffix: only letters, digits, . _ - are allowed."
  local kimg="kernel-$KVER$ksuffix"

  if [[ -e "$LAUNCH_DIR/$OUTNAME" && $force != 1 ]]; then
    die "$LAUNCH_DIR/$OUTNAME already exists (--force to overwrite)."
  fi
  if [[ $kern == 1 && -e "$LAUNCH_DIR/$kimg" && $force != 1 ]]; then
    die "$LAUNCH_DIR/$kimg already exists (--force to overwrite)."
  fi

  mkdir -p "$WORK"/{ctx,ksrc,out}
  zcat /proc/config.gz > "$WORK/config.run"
  emit_containerfile > "$WORK/ctx/Containerfile"
  emit_inner > "$WORK/inner.sh"

  # the seed is only needed if the tree is not already cached
  [[ -d "$WORK/ksrc/$TAG" ]] && seed=""
  [[ -z "$seed" || -f "$seed/Makefile" ]] || die "--seed '$seed' is not a kernel tree."

  local netarg=()
  [[ -n "${AFS_WSL_NET:-}" ]] && netarg=("--network=${AFS_WSL_NET}")

  log "Building image $IMAGE"
  podman build "${netarg[@]}" -t "$IMAGE" -f "$WORK/ctx/Containerfile" "$WORK/ctx"

  local args=(--rm "${netarg[@]}"
    -e KVER="$KVER" -e WANT="$only" -e LAYOUT="$layout" -e OUTNAME="$OUTNAME"
    -e FORCE="$force" -e REQUIRE_OPENAFS="$req"
    -e BUILD_KERNEL="$kern" -e TEST_MODE="$test_mode" -e KIMGNAME="$kimg"
    -e KAFS_RXGK="${KAFS_RXGK:-1}" -e KAFS_CACHEFILES="${KAFS_CACHEFILES:-1}"
    -e KAFS_ALLOW_Y="${KAFS_ALLOW_Y:-}"
    -v "$WORK:/work"
    -v "$LAUNCH_DIR:/out")
  if [[ "$only" != kafs ]]; then
    if [[ -d "$debs" ]]; then
      args+=(-v "$debs:/debs:ro")
    else
      [[ $req == 1 ]] && die "--debs '$debs' does not exist (run openafs-backports-podman.sh)."
      warn "$debs does not exist: openafs will be skipped (run openafs-backports-podman.sh)."
    fi
  fi
  [[ $test_mode == 0 ]] && args+=(-v "/lib/modules/$KVER:/host-modules:ro")
  [[ -n "$seed" ]] && args+=(-v "$seed:/seed:ro")

  log "Starting the build container (kernel $KVER, modules: $only, layout: $layout)"
  podman run "${args[@]}" "$IMAGE" bash /work/inner.sh

  print_next_steps "$test_mode" "$kern" "$kimg"
}

cmd_status() {
  echo "running kernel   : $KVER"
  echo "work directory   : $WORK"
  if command -v podman >/dev/null && podman image exists "$IMAGE" 2>/dev/null; then
    echo "image            : present ($IMAGE)"
  else
    echo "image            : absent"
  fi
  if [[ -f "$WORK/out/BUILD-INFO" ]]; then
    echo "--- last BUILD-INFO"; cat "$WORK/out/BUILD-INFO"
  fi
  echo "--- VHDX in the current directory:"
  ls -l "$LAUNCH_DIR"/wsl-modules-*.vhdx 2>/dev/null || echo "(none)"
  echo "--- /lib/modules/$KVER/extra:"
  ls "/lib/modules/$KVER/extra" 2>/dev/null || echo "(empty or absent)"
  echo "--- loaded modules:"; lsmod | grep -E '^(kafs|rxrpc|openafs)' || echo "(none)"
}

cmd_clean() {
  [[ "$WORK" == "$HOME"/* ]] || die "refusing to delete '$WORK' (outside \$HOME)."
  if [[ "${1:-}" != "-y" ]]; then
    read -r -p "Remove image $IMAGE and $WORK? [y/N] " a
    [[ "$a" == [yY] ]] || { echo "cancelled"; return 0; }
  fi
  if command -v podman >/dev/null; then
    podman rmi -f "$IMAGE" 2>/dev/null || true
    podman unshare rm -rf "$WORK"
  else
    rm -rf "$WORK"
  fi
  log "Cleaned (the VHDX files in the current directory were not touched)."
}

usage() { sed -n '/^# [a-z-]*\.sh$/,/^set -euo/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; }

case "${1:-build}" in
  build)               shift || true; cmd_build "$@" ;;
  -h|--help|help)      usage ;;
  --*)                 cmd_build "$@" ;;
  status)              cmd_status ;;
  clean)               shift; cmd_clean "${1:-}" ;;
  emit-containerfile)  emit_containerfile ;;
  emit-inner)          emit_inner ;;
  *)                   usage; exit 1 ;;
esac
