# wsl-modules-vhdx.sh
#
# Builds the kafs and/or OpenAFS kernel modules for the stock WSL2 kernel and packs them into a
# VHDX to use with `kernelModules=` in .wslconfig. Everything happens in a throwaway rootless
# Podman container: NOTHING is installed on your distro, and nothing is copied to Windows or
# changed in .wslconfig.
#
# Why a VHDX: /lib/modules/<ver> in WSL is an overlay whose writable layer lives on tmpfs, so
# .ko files copied into extra/ vanish when the VM stops. A VHDX set with kernelModules= is
# persistent.
#
# The VHDX REPLACES Microsoft's stock one (kernelModules= is a single disk; the stock one is only
# used when the option is empty): it therefore contains the stock modules + ours (in extra/), with
# modules.dep & co. regenerated by depmod. WSL also requires kernel= together with kernelModules=
# (otherwise it refuses to start): point it to a copy of the stock kernel of the SAME release.
# After every `wsl --update` everything must be redone (see README). kafs.ko and openafs.ko can
# live in the same VHDX (different names) but must NOT be loaded together: both register "afs".
#
# In the container (debian:trixie image):
#   1. clones the WSL2 kernel (tag = uname -r), applies the kafs options to your /proc/config.gz
#      (AF_RXRPC=m, RXKAD, AFS_FS=m, AFS_FSCACHE, + RXGK, CACHEFILES=m) and ABORTS if anything
#      would become built-in (=y); builds with gcc-13 up to Module.symvers.
#   2. kafs: keeps the modules that are NEW compared to /lib/modules/<ver>
#      (rxrpc, kafs, fcrypt, pcbc, ...).
#   3. openafs: builds openafs.ko with DKMS (container only) from the openafs-modules-dkms
#      package produced by openafs-backports-podman.sh.
#   4. checks vermagic and symbol CRCs of ALL the modules against the stock modules, then strips.
#   5. assembles the stock tree + extra/, depmod, ext4 with `mke2fs -d` (no root), qemu-img -> VHDX.
#
# The VHDX is written to the directory you run the script from (existing files are not overwritten).
#
# Usage:
#   ./wsl-modules-vhdx.sh [build] [options]
#   ./wsl-modules-vhdx.sh status
#   ./wsl-modules-vhdx.sh clean [-y]
#   ./wsl-modules-vhdx.sh emit-containerfile | emit-inner       # prints the generated files (debug)
#
# Build options:
#   --only kafs|openafs|both   which modules to include               (default: both)
#   --debs DIR                 openafs .deb files (from openafs-backports-podman.sh)
#                              (default: ./openafs-debs)
#   --require-openafs          error if openafs-modules-dkms is not available
#   --layout flat|nested       VHDX layout (default: flat, like Microsoft's stock VHD);
#                              nested adds linux-headers and an empty perf folder
#   --seed DIR                 already built kernel tree (same tag, gcc-13) to start from,
#                              to skip the full kernel build (~11 min the first time)
#   --kernel                   also builds the kernel image (bzImage; Image on arm64) as a
#                              compile test and copies it to ./kernel-<release>-built. It is NOT
#                              identical to Microsoft's and is not boot-tested: for kernel= the
#                              stock copy is still recommended.
#   --latest                   TEST MODE: use the newest Microsoft tag with the same major.minor
#                              (e.g. 6.18.58.1) instead of the running one. Builds the kernel
#                              (implies --kernel) + ALL the modules from the same build and creates
#                              a complete VHDX (no stock base) to try with kernel= and
#                              kernelModules=. Separate tree cache (~/.cache/wsl-modules/test-*).
#   --target-tag TAG           like --latest but with a specific tag (linux-msft-wsl-X.Y.Z[.N])
#   --kernel-suffix STR        suffix of the kernel image name: kernel-<release>STR
#                              (default: -built; "" gives plain kernel-<release>;
#                              allowed characters: letters, digits, . _ -)
#   --force                    overwrite the output VHDX (and kernel image) if they exist
#
# Environment variables (all optional):
#   KAFS_RXGK=0       do not enable RXGK                               (default: 1)
#   KAFS_CACHEFILES=0 do not build cachefiles.ko                       (default: 1)
#   KAFS_ALLOW_Y      symbols (space separated) allowed to become =y
#   WSLMOD_WORK       work/cache directory        (default: ~/.cache/wsl-modules)
#   WSLMOD_IMAGE      image name                  (default: localhost/wsl-modules-builder:trixie)
#   AFS_WSL_NET       e.g. "host" -> --network=host (if DNS inside the container does not work)

set -euo pipefail

LAUNCH_DIR="$PWD"                         # the VHDX goes here
WORK="${WSLMOD_WORK:-$HOME/.cache/wsl-modules}"
IMAGE="${WSLMOD_IMAGE:-localhost/wsl-modules-builder:trixie}"
KVER="$(uname -r)"
RUNKVER="$KVER"                           # KVER/TAG/OUTNAME/WORK change only in test mode
TAG="linux-msft-wsl-${KVER%%-*}"
OUTNAME="wsl-modules-$KVER.vhdx"

die() { echo "ERROR: $*" >&2; exit 1; }
log() { echo "==> $*"; }
warn() { echo "WARNING: $*" >&2; }

need_wsl_kernel() {
  [[ "$KVER" == *-microsoft-standard-WSL2 ]] ||
    die "kernel '$KVER' is not a stock Microsoft WSL2 kernel" \
        "(expected suffix: -microsoft-standard-WSL2)."
  [[ -r /proc/config.gz ]] || die "/proc/config.gz is not available."
  [[ -r "/lib/modules/$KVER/modules.order" ]] ||
    die "/lib/modules/$KVER/modules.order is not readable."
}

need_podman() {
  command -v podman >/dev/null ||
    die "podman is not installed. Install it with: sudo apt install podman"
  if ! podman info >/dev/null 2>&1; then
    podman info 2>&1 | tail -15 >&2 || true
    die "podman does not work in rootless mode" \
        "(see the error above; check /etc/subuid, uidmap, passt)."
  fi
}

# ---------------------------------------------------------------------------------------------
# Generated files
# ---------------------------------------------------------------------------------------------
emit_containerfile() {
cat <<'CFEOF'
FROM docker.io/library/debian:trixie
ENV DEBIAN_FRONTEND=noninteractive
RUN apt-get update \
 && apt-get install -y --no-install-recommends \
      build-essential gcc-13 git ca-certificates dkms rsync \
      bc bison flex libelf-dev libssl-dev dwarves cpio kmod perl python3 zstd xz-utils \
      e2fsprogs qemu-utils file \
 && rm -rf /var/lib/apt/lists/*
CFEOF
}

emit_inner() {
cat <<'INNEREOF'
#!/usr/bin/env bash
# Runs INSIDE the container. The kernel is the WSL distro's, so uname -r matches.
set -euo pipefail
: "${KVER:?KVER is not set}"

# Without LOCALVERSION set (even empty) scripts/setlocalversion appends a "+" to the release
# and the vermagic does not match. It must be exported for all make calls and for DKMS.
export LOCALVERSION=

TAG="linux-msft-wsl-${KVER%%-*}"
KSRC="/work/ksrc/$TAG"
OUT=/work/out
NPROC="$(nproc)"
WANT="${WANT:-both}"                       # kafs | openafs | both
LAYOUT="${LAYOUT:-flat}"                   # flat | nested
OUTNAME="${OUTNAME:?}"
WANT_RXGK="${KAFS_RXGK:-1}"
WANT_CACHEFILES="${KAFS_CACHEFILES:-1}"
ALLOW_Y_EXTRA="${KAFS_ALLOW_Y:-}"
WANT_KAFS=0; WANT_OPENAFS=0
[[ "$WANT" == kafs    || "$WANT" == both ]] && WANT_KAFS=1
[[ "$WANT" == openafs || "$WANT" == both ]] && WANT_OPENAFS=1

log() { echo "==> $*"; }
warn() { echo "WARNING: $*" >&2; }
die() { echo "ERROR: $*" >&2; exit 1; }

# 1 = kernel newer than the running one: kernel and modules are all built here
TEST_MODE="${TEST_MODE:-0}"
if [[ "$TEST_MODE" != 1 ]]; then
  [[ "$(uname -r)" == "$KVER" ]] ||
    die "uname -r in the container ('$(uname -r)') != KVER ('$KVER')."
  [[ -r /host-modules/modules.order && -d /host-modules/kernel ]] ||
    die "/host-modules (the host's stock modules) is not mounted."
fi
ROOT=/work/vhdx-root
[[ -d /out ]] || die "/out is not mounted."
if [[ -e "/out/$OUTNAME" && "${FORCE:-0}" != 1 ]]; then
  die "/out/$OUTNAME already exists (--force to overwrite)."
fi
BUILD_KERNEL="${BUILD_KERNEL:-0}"
KIMGNAME="${KIMGNAME:-kernel-$KVER-built}"
if [[ "$BUILD_KERNEL" == 1 && -e "/out/$KIMGNAME" && "${FORCE:-0}" != 1 ]]; then
  die "/out/$KIMGNAME already exists (--force to overwrite)."
fi
mkdir -p /work/ksrc
rm -rf "${OUT:?}"; mkdir -p "$OUT/kafs" "$OUT/openafs"

# --- compiler: gcc-13 for everything (the module_layout CRC depends on the compiler) ----------
KCC=gcc-13
command -v "$KCC" >/dev/null || die "$KCC is not installed in the image (rebuild the image)."
ln -sf "$(command -v "$KCC")" /usr/local/bin/gcc
hash -r
GCCV="$("$KCC" -dumpfullversion)"
log "Compiler: $(gcc --version | head -1)"

# --- stage 1: kernel tree (build tool only) ---------------------------------------------------
if [[ ! -d "$KSRC" ]]; then
  if [[ -d /seed ]]; then
    [[ -f /seed/Makefile ]] || die "/seed does not look like a kernel tree (Makefile missing)."
    log "Stage 1: copying the already built tree (seed)"
    mkdir -p "$KSRC"
    cp -a /seed/. "$KSRC/"
  else
    log "Stage 1: cloning $TAG"
    repo=https://github.com/microsoft/WSL2-Linux-Kernel.git
    git ls-remote --exit-code --tags "$repo" "refs/tags/$TAG" >/dev/null ||
      die "tag '$TAG' not found in the Microsoft repository."
    git clone --depth=1 --branch "$TAG" "$repo" "$KSRC"
  fi
else
  log "Stage 1: tree already present in $KSRC"
fi
cd "$KSRC"
# a tree (or seed) built with another gcc, or without a marker, must be cleaned
if [[ -s Module.symvers && "$(cat .wslmod-gcc 2>/dev/null || true)" != "$GCCV" ]]; then
  log "Tree built with another compiler (or unknown): make clean"
  make CC="$KCC" clean >/dev/null
fi
echo "$GCCV" > .wslmod-gcc

# --- stage 2: configuration -------------------------------------------------------------------
if [[ "$TEST_MODE" == 1 ]]; then
  log "Stage 2: configuration (baseline = Microsoft's config in the tree, after olddefconfig)"
  # release different from the running one: the baseline is the config Microsoft ships in the tree
  case "$(uname -m)" in
    x86_64)  cfg=Microsoft/config-wsl ;;
    aarch64) cfg=Microsoft/config-wsl-arm64 ;;
    *) die "architecture $(uname -m) is not supported." ;;
  esac
  [[ -f "$cfg" ]] || die "$cfg not found in the tree."
  cp "$cfg" .config
else
  log "Stage 2: configuration (baseline = your /proc/config.gz, after olddefconfig)"
  cp /work/config.run .config
fi
make CC="$KCC" olddefconfig >/dev/null
cp .config /work/config.base

if ((WANT_KAFS)); then
  SC=./scripts/config
  "$SC" --module AF_RXRPC --enable AF_RXRPC_IPV6 --enable RXKAD \
        --module AFS_FS --enable AFS_FSCACHE
  [[ "$WANT_RXGK" == 1 ]]       && "$SC" --enable RXGK
  [[ "$WANT_CACHEFILES" == 1 ]] && "$SC" --module CACHEFILES
  make CC="$KCC" olddefconfig >/dev/null

  missing=()
  want() {
    local s; s="$("$SC" --state "$1")"
    [[ "$s" == "$2" ]] || missing+=("$1: wanted $2, got $s")
  }
  want AF_RXRPC m; want AF_RXRPC_IPV6 y; want RXKAD y; want AFS_FS m; want AFS_FSCACHE y
  [[ "$WANT_RXGK" == 1 ]]       && want RXGK y
  [[ "$WANT_CACHEFILES" == 1 ]] && want CACHEFILES m
  if ((${#missing[@]})); then
    printf 'ERROR: options not applied by olddefconfig:\n  %s\n' "${missing[@]}" >&2
    exit 1
  fi
fi

rel="$(make CC="$KCC" -s kernelrelease)"
[[ "$rel" == "$KVER" ]] ||
  die "kernelrelease of the tree ('$rel') != expected release ('$KVER'):" \
      "the vermagic would not match."

# no option may become built-in: the running kernel does not contain that code.
sym_state() { sed -n "s/^CONFIG_\([A-Za-z0-9_]*\)=$2\$/\1/p" "$1" | sort -u; }
log "Options changed compared to the baseline (n/m -> m):"
comm -13 <(sym_state /work/config.base m) <(sym_state .config m) | sed 's/^/    =m  /'
comm -13 <(sym_state /work/config.base y) <(sym_state .config y) > /work/new-y.txt
ALLOW='^(AF_RXRPC_IPV6|RXKAD|RXGK|AFS_FSCACHE|AFS_DEBUG|AFS_DEBUG_CURSOR'
ALLOW+='|AF_RXRPC_DEBUG|AF_RXRPC_INJECT_.*|CACHEFILES_.*)$'
badY=()
while read -r s; do
  [[ -n "$s" ]] || continue
  [[ "$s" =~ $ALLOW ]] && continue
  for a in $ALLOW_Y_EXTRA; do [[ "$s" == "$a" ]] && continue 2; done
  badY+=("$s")
done < /work/new-y.txt
if ((${#badY[@]})); then
  echo "ERROR: these options would become built-in (=y) and the stock kernel does NOT" \
       "contain them:" >&2
  printf '  %s\n' "${badY[@]}" >&2
  echo "If they are only bools used by the modules (false alarm), repeat with" \
       "KAFS_ALLOW_Y=\"${badY[*]}\";" >&2
  echo "otherwise a rebuilt kernel is needed: stop and reassess." >&2
  exit 1
fi
log "No new built-in options beyond the allow-list."

# --- stage 3: build ---------------------------------------------------------------------------
log "Stage 3: make modules (long without a seed: it also produces vmlinux and Module.symvers)"
make CC="$KCC" -j"$NPROC" modules
[[ -s Module.symvers ]] || die "Module.symvers missing after the build."
log "module_layout CRC in the tree: $(grep -w module_layout Module.symvers | awk '{print $1}')"

# --- stage 3b (optional): kernel image as a compile test --------------------------------------
KIMG_INFO=""
if [[ "$BUILD_KERNEL" == 1 ]]; then
  case "$(uname -m)" in
    x86_64)  KTARGET=bzImage; KIMGPATH=arch/x86/boot/bzImage ;;
    aarch64) KTARGET=Image;   KIMGPATH=arch/arm64/boot/Image ;;
    *) die "architecture $(uname -m) is not supported for --kernel." ;;
  esac
  log "Stage 3b: make $KTARGET (kernel image compile test)"
  make CC="$KCC" -j"$NPROC" "$KTARGET"
  [[ -s "$KIMGPATH" ]] || die "$KIMGPATH was not produced."
  kimg_ver="$(file -b "$KIMGPATH")"
  case "$kimg_ver" in
    *"version $KVER "*|*"version $KVER,"*) : ;;
    *) die "the image does not report release '$KVER': $kimg_ver" ;;
  esac
  rm -f "/out/$KIMGNAME"
  install -m 0644 "$KIMGPATH" "/out/$KIMGNAME"
  KIMG_INFO="$KIMGNAME ($(stat -c %s "/out/$KIMGNAME") bytes)"
  KIMG_INFO+=" sha256 $(sha256sum "/out/$KIMGNAME" | awk '{print $1}')"
  log "Kernel image: $KIMG_INFO"
fi

# --- stage 4: kafs modules = the ones that are new compared to the host -----------------------
if [[ "$TEST_MODE" == 1 ]]; then
  # kernel and modules come out of the SAME build: install the whole module tree (no stock base)
  log "Stage 4: modules_install of the whole tree into $ROOT"
  rm -rf "${ROOT:?}"; mkdir -p "$ROOT"
  make CC="$KCC" -j"$NPROC" modules_install INSTALL_MOD_PATH="$ROOT" INSTALL_MOD_STRIP=1 >/dev/null
  rm -f "$ROOT/lib/modules/$KVER/build" "$ROOT/lib/modules/$KVER/source"
  if ((WANT_KAFS)); then
    for m in rxrpc kafs cachefiles fcrypt pcbc krb5 krb5enc camellia_generic; do
      f="$(find "$ROOT/lib/modules/$KVER" -name "$m.ko" | head -1)"
      [[ -n "$f" ]] && install -m 0644 "$f" "$OUT/kafs/$m.ko"
    done
    for m in rxrpc kafs; do
      [[ -f "$OUT/kafs/$m.ko" ]] ||
        die "$m.ko not installed by modules_install (config: MODULE_COMPRESS?)."
    done
    log "kafs modules present: $(find "$OUT/kafs" -name '*.ko' -printf '%f ')"
  fi
elif ((WANT_KAFS)); then
  log "Stage 4: kafs modules (new compared to /lib/modules/$KVER)"
  declare -A HOST
  while read -r p; do
    b="$(basename "$p")"; b="${b%%.ko*}"; HOST["${b//-/_}"]=1
  done < /host-modules/modules.order
  while IFS= read -r -d '' ko; do
    n="$(basename "$ko" .ko)"
    [[ -n "${HOST[${n//-/_}]:-}" ]] && continue
    install -m 0644 "$ko" "$OUT/kafs/$n.ko"
    echo "    new: ${ko#"$KSRC"/}"
  done < <(find "$KSRC" -name '*.ko' -print0)
  for m in rxrpc kafs; do [[ -f "$OUT/kafs/$m.ko" ]] || die "$m.ko was not produced."; done
fi

# --- stage 5: openafs.ko with DKMS (container only) -------------------------------------------
if ((WANT_OPENAFS)); then
  log "Stage 5: openafs module with DKMS"
  shopt -s nullglob
  debs=(/debs/openafs-modules-dkms_*.deb)
  shopt -u nullglob
  if ((${#debs[@]} == 0)); then
    if [[ "${REQUIRE_OPENAFS:-0}" == 1 ]]; then
      die "openafs-modules-dkms_*.deb not found in /debs."
    fi
    warn "openafs-modules-dkms_*.deb not found (run openafs-backports-podman.sh): skipping openafs."
  else
    if [[ -f /debs/BUILD-INFO ]]; then
      log "BUILD-INFO of the .deb files:"; sed 's/^/    /' /debs/BUILD-INFO
    fi
    deb="$(printf '%s\n' "${debs[@]}" | sort -V | tail -1)"
    mkdir -p "/lib/modules/$KVER"
    ln -sfn "$KSRC" "/lib/modules/$KVER/build"
    ln -sfn "$KSRC" "/lib/modules/$KVER/source"
    root="$(mktemp -d)"
    dpkg-deb -x "$deb" "$root"            # no postinst: DKMS is launched explicitly
    src="$(find "$root/usr/src" -maxdepth 1 -type d -name 'openafs-*' | head -1)"
    [[ -n "$src" ]] || die "DKMS source not found in the package."
    ver="$(basename "$src")"; ver="${ver#openafs-}"
    log "DKMS module: openafs/$ver for $KVER"
    rm -rf "/usr/src/openafs-$ver" /var/lib/dkms/openafs
    cp -a "$src" "/usr/src/openafs-$ver"
    dkms add -m openafs -v "$ver"
    dkms build -m openafs -v "$ver" -k "$KVER"
    ko="$(find "/var/lib/dkms/openafs/$ver/$KVER" -type f \
               \( -name 'openafs.ko' -o -name 'openafs.ko.*' \) | head -1)"
    [[ -n "$ko" ]] ||
      die "openafs.ko not produced by DKMS (see /var/lib/dkms/openafs/$ver/build/make.log)."
    case "$ko" in
      *.zst) zstd -dc "$ko" > "$OUT/openafs/openafs.ko" ;;
      *.xz)  xz   -dc "$ko" > "$OUT/openafs/openafs.ko" ;;
      *)     cp "$ko" "$OUT/openafs/openafs.ko" ;;
    esac
    echo "$ver" > "$OUT/openafs/VERSION"
    rm -rf "$root"
  fi
fi

shopt -s nullglob
NEWKO=("$OUT"/kafs/*.ko "$OUT"/openafs/*.ko)
shopt -u nullglob
((${#NEWKO[@]})) || die "no module to pack."

# --- stage 6: strip and ABI check against the stock modules -----------------------------------
if [[ "$TEST_MODE" == 1 ]]; then
  log "Stage 6: stripping debug info and checking vermagic/CRC against the build's Module.symvers"
else
  log "Stage 6: stripping debug info and checking vermagic/CRC against the stock modules"
fi
for ko in "${NEWKO[@]}"; do strip --strip-debug "$ko"; done

# sequential: with xargs -P lines from different processes get mixed and produce false MISMATCHes
if [[ "$TEST_MODE" == 1 ]]; then
  # no stock modules for this release: the base is the Module.symvers of the same kernel build
  awk -F'\t' '/^0x[0-9a-f]{8}\t/ {print $1 "\t" $2}' Module.symvers | sort -u > /work/host-crc.tsv
  [[ -s /work/host-crc.tsv ]] || die "Module.symvers is empty or unreadable."
  log "CRCs from the build: $(wc -l < /work/host-crc.tsv) symbols (Module.symvers)"
  nbad=0
  while IFS= read -r -d '' ko; do
    vm="$(modinfo -F vermagic "$ko")"
    if [[ "${vm%% *}" != "$KVER" ]]; then
      echo "ERROR: ${ko#"$ROOT"/}: vermagic '${vm%% *}' != '$KVER'" >&2
      nbad=$((nbad+1))
    fi
  done < <(find "$ROOT/lib/modules/$KVER" -name '*.ko' -print0)
  ((nbad == 0)) || die "$nbad modules with the wrong vermagic."
  log "vermagic of all installed modules = $KVER"
else
  find /host-modules/kernel -name '*.ko*' -print0 2>/dev/null |
    xargs -0 -r -n1 modprobe --dump-modversions 2>/dev/null |
    grep -E '^0x[0-9a-f]{8}'"$(printf '\t')" | sort -u > /work/host-crc.tsv || true
  [[ -s /work/host-crc.tsv ]] || die "cannot read the CRCs of the stock modules."
  layout_crc="$(awk -F'\t' '$2=="module_layout"{print $1}' /work/host-crc.tsv |
                sort -u | tr '\n' ' ')"
  log "Known stock CRCs: $(wc -l < /work/host-crc.tsv) symbols; module_layout: $layout_crc"
fi

fail=0
for ko in "${NEWKO[@]}"; do
  m="$(basename "$ko")"
  vm="$(modinfo -F vermagic "$ko")"
  [[ "${vm%% *}" == "$KVER" ]] || { echo "ERROR: $m: vermagic '${vm%% *}' != '$KVER'" >&2; fail=1; }
  case "$vm" in *modversions*) : ;; *) warn "$m: vermagic without 'modversions'." ;; esac
  modprobe --dump-modversions "$ko" | sort -u > /work/mod-crc.tsv
  res="$(awk -F'\t' '
    NR == FNR  { h[$2] = $1; next }
    ($2 in h)  {
      if (h[$2] == $1) ok++
      else { print "MISMATCH " $2 " base=" h[$2] " module=" $1; bad++ }
      next
    }
               { unk++ }
    END        { printf "OK=%d MISMATCH=%d UNVERIFIABLE=%d\n", ok, bad, unk }
  ' /work/host-crc.tsv /work/mod-crc.tsv)"
  echo "    $m: $(tail -1 <<<"$res")"
  if grep -q '^MISMATCH' <<<"$res"; then grep '^MISMATCH' <<<"$res" >&2; fail=1; fi
done
((fail == 0)) || die "ABI check failed: the modules would not be loadable in kernel $KVER."

# --- stage 7: assembling the tree and the VHDX ------------------------------------------------
log "Stage 7: assembling (layout: $LAYOUT)"
TREE="$ROOT/lib/modules/$KVER"
if [[ "$TEST_MODE" == 1 ]]; then
  # tree already installed in stage 4; only openafs.ko (out of tree) goes into extra/
  EXTRAKO=("$OUT"/openafs/*.ko)
  [[ -e "${EXTRAKO[0]}" ]] || EXTRAKO=()
else
  rm -rf "$ROOT"; mkdir -p "$TREE"
  # --no-owner/--no-group: root-owned host files appear as "nobody" in the container; this way
  # they end up as root:root in the image.
  rsync -rlpt --no-owner --no-group \
        --exclude=/build --exclude=/source --exclude=/lost+found --exclude=/rw \
        /host-modules/ "$TREE/"
  EXTRAKO=("${NEWKO[@]}")
fi
if ((${#EXTRAKO[@]})); then
  mkdir -p "$TREE/extra"
  # our names replace any previous copies; foreign modules in extra/ are kept
  for ko in "${EXTRAKO[@]}"; do rm -f "$TREE/extra/$(basename "$ko")"; done
  for ko in "${EXTRAKO[@]}"; do install -m 0644 "$ko" "$TREE/extra/"; done
fi

depmod -b "$ROOT" "$KVER"
for ko in "${EXTRAKO[@]}"; do
  grep -q "^extra/$(basename "$ko"):" "$TREE/modules.dep" ||
    die "$(basename "$ko") missing from modules.dep after depmod."
done
if [[ "$TEST_MODE" == 1 ]] && ((WANT_KAFS)); then
  grep -Eq '(^|/)kafs\.ko:' "$TREE/modules.dep" ||
    die "kafs.ko missing from modules.dep after depmod."
fi
log "modules.dep: $(grep -c '' "$TREE/modules.dep") modules, new ones included."

IMGSRC="$TREE"
if [[ "$LAYOUT" == nested ]]; then
  # nested layout: <release>/{modules,linux-headers,perf};
  # WSL recreates the build -> linux-headers link
  STAGE=/work/vhdx-stage
  rm -rf "$STAGE"; mkdir -p "$STAGE/$KVER/linux-headers" "$STAGE/$KVER/perf"
  cp -a "$TREE" "$STAGE/$KVER/modules"
  make -C "$KSRC" CC="$KCC" -s headers_install INSTALL_HDR_PATH="$STAGE/$KVER/linux-headers"
  IMGSRC="$STAGE"
fi

size=$(du -bs "$IMGSRC" | awk '{print $1}')
size=$((size + 256 * (1 << 20)))
inodes=$(( $(find "$IMGSRC" | wc -l) + 4096 ))
rm -f /work/modules.img
mke2fs -q -L '' -d "$IMGSRC" -N "$inodes" -b 1024 -t ext4 /work/modules.img $((size / 1024))

# --- stage 8: checking the image without mounting it ------------------------------------------
log "Stage 8: checking the image (without mounting it)"
e2fsck -fn /work/modules.img >/dev/null || die "e2fsck reports errors in the image."
EXTRA_PATH=/extra; [[ "$LAYOUT" == nested ]] && EXTRA_PATH="/$KVER/modules/extra"
if ((${#EXTRAKO[@]})); then
  listing="$(debugfs -R "ls -l $EXTRA_PATH" /work/modules.img 2>/dev/null)"
  for ko in "${EXTRAKO[@]}"; do
    grep -q "$(basename "$ko")" <<<"$listing" ||
      die "$(basename "$ko") not present in $EXTRA_PATH in the image."
  done
  echo "    $EXTRA_PATH in the image contains the expected modules."
fi

rm -f "/out/$OUTNAME"
qemu-img convert -O vhdx /work/modules.img "/out/$OUTNAME"
rm -f /work/modules.img
qemu-img info "/out/$OUTNAME" | sed 's/^/    /'

{
  echo "kernel:   $KVER"
  [[ "$TEST_MODE" == 1 ]] &&
    echo "mode:     SELF-BUILT kernel (not Microsoft's) + all modules from the same build"
  echo "tag:      $TAG"
  echo "layout:   $LAYOUT"
  echo "gcc:      $(gcc --version | head -1)"
  echo "modules:  $(for k in "${NEWKO[@]}"; do basename "$k"; done | tr '\n' ' ')"
  [[ -f "$OUT/openafs/VERSION" ]] && echo "openafs:  $(cat "$OUT/openafs/VERSION")"
  echo "rxgk:     $WANT_RXGK  cachefiles: $WANT_CACHEFILES"
  [[ -n "$KIMG_INFO" ]] && echo "image:    $KIMG_INFO"
  echo "date:     $(date -u +%FT%TZ)"
  echo "sha256:   $(sha256sum "/out/$OUTNAME" | awk '{print $1}')"
} > "$OUT/BUILD-INFO"
log "Done."
cat "$OUT/BUILD-INFO"
INNEREOF
}

